def generate_code(
    arch_index: int,
    val_accuracy: float = 0.0,
    extrapolated: float = 0.0,
    params: int = 0,
    flops: float = 0.0,
    github_user: str = 'danielomoteshohacks',
) -> str:
    """
    Generate a complete, runnable PyTorch file for the given architecture.

    Every field in the template is filled in with real values from
    the search results. The output is a .py file the user can run
    directly to train the discovered architecture to convergence.
    """
    arch    = get_arch_info(arch_index)
    ops     = arch['operations']
    edges   = arch['edges']

    # Build the human-readable edge comments for the docstring
    edge_comments = '\n'.join(
        f'        Edge {e["edge_index"]} (node {e["source"]} → node {e["target"]})'
        f': {e["operation"]}'
        for e in edges
    )

    return _TEMPLATE.format(
        arch_index     = arch_index,
        arch_string    = arch['arch_string'],
        operations     = ops,
        val_accuracy   = val_accuracy,
        extrapolated   = extrapolated,
        params         = params,
        flops          = flops,
        github_user    = github_user,
        edge_comments  = edge_comments,
        edges          = repr(EDGES),
        op_list        = repr(ops),
    )