class ConvBnRelu(nn.Module):
    """Convolution → BatchNorm → ReLU. Standard vision building block."""

    def __init__(self, in_ch, out_ch, kernel, stride=1, padding=0):
        super().__init__()
        self.op = nn.Sequential(
            nn.Conv2d(in_ch, out_ch, kernel,
                      stride=stride, padding=padding, bias=False),
            nn.BatchNorm2d(out_ch),
            nn.ReLU(inplace=True),
        )

    def forward(self, x):
        return self.op(x)


class CellOp(nn.Module):
    """One operation on one edge of the cell DAG."""

    def __init__(self, op_name: str, channels: int):
        super().__init__()
        self.op_name = op_name

        ops = {{
            'none':         lambda: None,
            'skip_connect': nn.Identity,
            'nor_conv_1x1': lambda: ConvBnRelu(channels, channels, 1, padding=0),
            'nor_conv_3x3': lambda: ConvBnRelu(channels, channels, 3, padding=1),
            'avg_pool_3x3': lambda: nn.AvgPool2d(3, stride=1, padding=1),
        }}
        self.op = ops[op_name]()

    def forward(self, x):
        if self.op is None:
            return torch.zeros_like(x)
        return self.op(x)


class NASCell(nn.Module):
    """
    The searched cell — a DAG with 4 nodes and 6 directed edges.

    Topology:
        Node 0 (input)  →  Node 1, 2, 3
        Node 1          →  Node 2, 3
        Node 2          →  Node 3 (output)

    Each node sums all incoming edge outputs.
    Operations per edge:
{edge_comments}
    """

    EDGES = {edges}

    def __init__(self, channels: int):
        super().__init__()
        operations = {op_list}
        self.ops   = nn.ModuleList([
            CellOp(op, channels) for op in operations
        ])

    def forward(self, x):
        nodes = [None] * 4
        nodes[0] = x

        for i, (src, tgt) in enumerate(self.EDGES):
            out = self.ops[i](nodes[src])
            nodes[tgt] = out if nodes[tgt] is None else nodes[tgt] + out

        return nodes[3] if nodes[3] is not None else torch.zeros_like(x)


class NASNetwork(nn.Module):
    """
    Full network: stem → 3 stages of NASCells → classifier.
    Faithful to the NAS-Bench-201 macro skeleton.
    """

    def __init__(self, num_classes: int = 10, channels: int = 16,
                 cells_per_stage: int = 3):
        super().__init__()

        self.stem = ConvBnRelu(3, channels, 3, padding=1)

        self.stage1 = nn.Sequential(*[NASCell(channels) for _ in range(cells_per_stage)])
        self.down1  = ConvBnRelu(channels, channels * 2, 3, stride=2, padding=1)

        self.stage2 = nn.Sequential(*[NASCell(channels * 2) for _ in range(cells_per_stage)])
        self.down2  = ConvBnRelu(channels * 2, channels * 4, 3, stride=2, padding=1)

        self.stage3 = nn.Sequential(*[NASCell(channels * 4) for _ in range(cells_per_stage)])

        self.gap        = nn.AdaptiveAvgPool2d(1)
        self.classifier = nn.Linear(channels * 4, num_classes)

    def forward(self, x):
        x = self.stem(x)
        x = self.stage1(x)
        x = self.down1(x)
        x = self.stage2(x)
        x = self.down2(x)
        x = self.stage3(x)
        x = self.gap(x).view(x.size(0), -1)
        return self.classifier(x)


